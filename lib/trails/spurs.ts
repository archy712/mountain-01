/**
 * 지선(곁길) 코스 큐레이션 (Task 034).
 *
 * 본선 탐방로 중간 갈림길에서 갈라지는 짧은 지선은 단독 코스로 보이면 오해를 준다(예: 한라산
 * "사라오름입구 ~ 사라오름"은 성판악 본선을 한참 오른 갈림길에서 진입하는 0.5km 곁길인데
 * 들머리처럼 보이고 "매우 쉬움/20분"이 접근 난이도를 과소평가한다).
 *
 * 위상(노드 그래프)만으로는 '도로변 들머리 막다른 끝'과 '정상 곁길 막다른 끝'을 구분할 수 없어
 * (둘 다 동일 패턴) 자동 판별이 불가능하다. 따라서 명백한 지선만 **KNPS 탐방코스명으로 수작업
 * 큐레이션**한다. 새 지선을 발견하면 이 집합에 이름을 추가한다.
 */
const SPUR_TRAIL_NAMES = new Set<string>([
  "사라오름입구 ~ 사라오름", // 한라산 — 성판악 본선 갈림길(사라오름입구)에서 진입
]);

/** 탐방코스명이 지선(곁길) 큐레이션 목록에 있는지. */
export function isSpurTrail(name: string): boolean {
  return SPUR_TRAIL_NAMES.has(name.trim());
}
